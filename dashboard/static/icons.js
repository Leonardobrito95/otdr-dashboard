function lucide(nome, tamanho, extra) {
  tamanho = tamanho || 16;
  extra = extra || '';
  const inner = LUCIDE_ICONS[nome];
  if (!inner) return '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${tamanho}" height="${tamanho}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide-icon ${extra}" style="vertical-align:-2px">${inner}</svg>`;
}

// Substitui elementos <i data-lucide="nome" data-size="16"></i> já presentes no HTML estático.
function aplicarIconesEstaticos() {
  document.querySelectorAll('[data-lucide]').forEach(el => {
    const nome = el.getAttribute('data-lucide');
    const tamanho = el.getAttribute('data-size') || 16;
    const extra = el.getAttribute('data-class') || '';
    el.outerHTML = lucide(nome, tamanho, extra);
  });
}
document.addEventListener('DOMContentLoaded', aplicarIconesEstaticos);
